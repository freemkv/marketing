#!/usr/bin/env python3
"""Build the freemkv APT repository served at https://freemkv.org/apt.

Only the index lives on the site: the .deb payloads stay on GitHub releases and
public/_redirects sends /apt/pool/... to the release asset (302).

For every source repo, every *.deb asset on its LATEST release is picked up,
any package, any architecture; nothing here names a package or an arch. The
newest version of each (package, arch) wins. Output:

  public/apt/dists/stable/main/binary-<arch>/Packages{,.gz}
  public/apt/dists/stable/{Release,InRelease,Release.gpg}
  public/_redirects   (generated block between the BEGIN/END apt markers)

Deterministic: Date is the newest release's publish time and the .gz has no
timestamp, so a rerun with no new release rewrites nothing. The Release is only
re-signed when its content changes (signatures carry a timestamp).

Needs: python3, dpkg-deb, dpkg (version compare), gpg with the signing key
imported (APT_KEY_ID selects it). GH_TOKEN is used for the GitHub API if set.
"""
import email.utils
import gzip
import hashlib
import io
import json
import os
import subprocess
import sys
import tempfile
import urllib.request
from datetime import datetime
from pathlib import Path

SOURCES = ["freemkv/freemkv", "freemkv/freemkv-firmware"]
ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public"
APT = PUBLIC / "apt"
DIST = APT / "dists" / "stable"
REDIRECTS = PUBLIC / "_redirects"
BEGIN = "# BEGIN apt (generated by scripts/apt-repo.py; do not edit by hand)"
END = "# END apt"
# Field order for each Packages stanza (anything else keeps control order,
# before Description, which stays last because it is multi-line).
INSERT = ["Filename", "Size", "MD5sum", "SHA1", "SHA256"]


def api(path):
    req = urllib.request.Request("https://api.github.com" + path)
    req.add_header("Accept", "application/vnd.github+json")
    tok = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
    if tok:
        req.add_header("Authorization", "Bearer " + tok)
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        raise


def download(url, dest):
    req = urllib.request.Request(url, headers={"Accept": "application/octet-stream"})
    with urllib.request.urlopen(req, timeout=600) as r, open(dest, "wb") as f:
        while chunk := r.read(1 << 20):
            f.write(chunk)


def control(deb):
    """Control file of a .deb as an ordered list of (field, value) pairs."""
    text = subprocess.run(["dpkg-deb", "-f", str(deb)], check=True,
                          capture_output=True, text=True).stdout
    fields = []
    for line in text.splitlines():
        if not line.strip():
            continue
        if line[0] in " \t":
            k, v = fields[-1]
            fields[-1] = (k, v + "\n" + line)
        else:
            k, _, v = line.partition(":")
            fields.append((k.strip(), v.strip()))
    return fields


def newer(a, b):
    return subprocess.run(["dpkg", "--compare-versions", a, "gt", b]).returncode == 0


def digests(path):
    hs = {n: hashlib.new(n) for n in ("md5", "sha1", "sha256")}
    with open(path, "rb") as f:
        while chunk := f.read(1 << 20):
            for h in hs.values():
                h.update(chunk)
    return {k: h.hexdigest() for k, h in hs.items()}


def stanza(fields, extra):
    out = [(k, v) for k, v in fields if k not in INSERT]
    names = [k for k, _ in out]
    at = names.index("Description") if "Description" in names else len(out)
    out[at:at] = [(k, extra[k]) for k in INSERT]
    return "".join(f"{k}: {v}\n" for k, v in out)


def write_if_changed(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_bytes() == data:
        return False
    path.write_bytes(data)
    return True


def main():
    work = Path(tempfile.mkdtemp(prefix="apt-repo-"))
    best = {}   # (package, arch) -> entry
    dates = []
    for repo in SOURCES:
        rel = api(f"/repos/{repo}/releases/latest")
        if not rel:
            print(f"{repo}: no published release, skipped")
            continue
        debs = [a for a in rel.get("assets", []) if a["name"].endswith(".deb")]
        if not debs:
            print(f"{repo} {rel['tag_name']}: no .deb assets, skipped")
            continue
        dates.append(rel["published_at"])
        for a in sorted(debs, key=lambda a: a["name"]):
            dest = work / f"{a['id']}.deb"
            download(a["browser_download_url"], dest)
            fields = control(dest)
            f = dict(fields)
            pkg, ver, arch = f["Package"], f["Version"], f["Architecture"]
            print(f"{repo} {rel['tag_name']}: {a['name']} -> {pkg} {ver} {arch}")
            key = (pkg, arch)
            if key in best and not newer(ver, best[key]["version"]):
                continue
            noepoch = ver.split(":", 1)[-1]
            best[key] = {
                "package": pkg, "version": ver, "arch": arch, "fields": fields,
                "pool": f"pool/main/{pkg}/{pkg}_{noepoch}_{arch}.deb",
                "url": a["browser_download_url"], "size": dest.stat().st_size,
                "hash": digests(dest),
            }
    if not best:
        sys.exit("no .deb assets found on any source release; refusing to publish an empty repo")

    entries = sorted(best.values(), key=lambda e: (e["package"], e["arch"]))
    arches = sorted({e["arch"] for e in entries if e["arch"] != "all"}) or ["all"]
    # Arch: all packages go into every concrete arch index (works on every apt).
    index = {}
    for arch in arches:
        text = "\n".join(
            stanza(e["fields"], {
                "Filename": e["pool"], "Size": str(e["size"]),
                "MD5sum": e["hash"]["md5"], "SHA1": e["hash"]["sha1"],
                "SHA256": e["hash"]["sha256"],
            })
            for e in entries if e["arch"] in (arch, "all"))
        raw = text.encode()
        buf = io.BytesIO()
        with gzip.GzipFile(filename="", mode="wb", fileobj=buf, mtime=0, compresslevel=9) as gz:
            gz.write(raw)
        index[f"main/binary-{arch}/Packages"] = raw
        index[f"main/binary-{arch}/Packages.gz"] = buf.getvalue()

    # Drop index dirs for arches that no longer exist.
    main_dir = DIST / "main"
    if main_dir.exists():
        for d in main_dir.iterdir():
            if d.name.startswith("binary-") and d.name[7:] not in arches:
                for f in d.iterdir():
                    f.unlink()
                d.rmdir()
    for rel_path, data in index.items():
        write_if_changed(DIST / rel_path, data)

    date = max(datetime.fromisoformat(d.replace("Z", "+00:00")) for d in dates)
    lines = [
        "Origin: freemkv",
        "Label: freemkv",
        "Suite: stable",
        "Codename: stable",
        "Date: " + email.utils.format_datetime(date, usegmt=True),
        "Architectures: " + " ".join(arches),
        "Components: main",
        "Description: freemkv packages (https://freemkv.org/apt)",
        "MD5Sum:",
        *(f" {hashlib.md5(d).hexdigest()} {len(d):>16} {p}" for p, d in sorted(index.items())),
        "SHA256:",
        *(f" {hashlib.sha256(d).hexdigest()} {len(d):>16} {p}" for p, d in sorted(index.items())),
    ]
    release = ("\n".join(lines) + "\n").encode()
    signed = (DIST / "InRelease").exists() and (DIST / "Release.gpg").exists()
    if write_if_changed(DIST / "Release", release) or not signed:
        key = os.environ.get("APT_KEY_ID")
        if not key:
            sys.exit("Release changed but APT_KEY_ID is not set; cannot sign")
        gpg = ["gpg", "--batch", "--yes", "--pinentry-mode", "loopback", "--passphrase", "",
               "--local-user", key, "--digest-algo", "SHA512"]
        subprocess.run(gpg + ["--clearsign", "-o", str(DIST / "InRelease"), str(DIST / "Release")], check=True)
        subprocess.run(gpg + ["--armor", "--detach-sign", "-o", str(DIST / "Release.gpg"), str(DIST / "Release")], check=True)
        print("Release changed: re-signed InRelease and Release.gpg")
    else:
        print("Release unchanged: signatures kept")

    # Cloudflare Pages redirects: pool path -> GitHub release asset.
    block = [BEGIN] + [f"/apt/{e['pool']} {e['url']} 302" for e in entries] + [END]
    old = REDIRECTS.read_text() if REDIRECTS.exists() else ""
    keep, skipping = [], False
    for line in old.splitlines():
        if line == BEGIN:
            skipping = True
        elif line == END and skipping:
            skipping = False
        elif not skipping:
            keep.append(line)
    while keep and not keep[-1].strip():
        keep.pop()
    new = "\n".join(keep + ([""] if keep else []) + block) + "\n"
    write_if_changed(REDIRECTS, new.encode())


if __name__ == "__main__":
    main()
