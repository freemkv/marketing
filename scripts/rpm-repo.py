#!/usr/bin/env python3
"""Build the freemkv RPM (dnf/zypper) repository served at https://freemkv.org/rpm.

Same design as scripts/apt-repo.py: only the metadata lives on the site; the
.rpm payloads stay on GitHub releases and public/_redirects sends
/rpm/packages/... to the release asset (302).

For every source repo, every *.rpm asset on its LATEST release is picked up,
any package, any architecture; nothing here names a package or an arch. The
newest version of each (name, arch) wins. Output:

  public/rpm/repodata/*            createrepo_c metadata (gzip, readable everywhere)
  public/rpm/repodata/repomd.xml.asc   detached signature (repo_gpgcheck)
  public/rpm/freemkv.repo          the .repo file users install
  public/rpm/freemkv.asc           the signing key (same key as /apt)
  public/rpm/sources.json          what the metadata was built from
  public/_redirects                (generated block between the BEGIN/END rpm markers)

Deterministic: if sources.json would not change, nothing is rewritten or re-signed.

Needs: python3, rpm (rpm -qp), createrepo_c, gpg with the signing key imported
(RPM_KEY_ID selects it). GH_TOKEN is used for the GitHub API if set.
"""
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from datetime import datetime
from pathlib import Path

SOURCES = ["freemkv/freemkv", "freemkv/freemkv-firmware"]
ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public"
RPM = PUBLIC / "rpm"
REDIRECTS = PUBLIC / "_redirects"
BEGIN = "# BEGIN rpm (generated by scripts/rpm-repo.py; do not edit by hand)"
END = "# END rpm"
REPO_FILE = """[freemkv]
name=freemkv
baseurl=https://freemkv.org/rpm
type=rpm-md
enabled=1
autorefresh=1
gpgcheck=1
repo_gpgcheck=1
gpgkey=https://freemkv.org/rpm/freemkv.asc
"""


def api(path):
    req = urllib.request.Request("https://api.github.com" + path)
    req.add_header("Accept", "application/vnd.github+json")
    tok = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
    if tok:
        req.add_header("Authorization", "Bearer " + tok)
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        raise


def download(url, dest):
    req = urllib.request.Request(url, headers={"Accept": "application/octet-stream"})
    with urllib.request.urlopen(req, timeout=600) as r, open(dest, "wb") as f:
        while chunk := r.read(1 << 20):
            f.write(chunk)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(1 << 20):
            h.update(chunk)
    return h.hexdigest()


def query(rpm):
    fmt = "%{NAME}\t%{EPOCHNUM}\t%{VERSION}\t%{RELEASE}\t%{ARCH}\t%{SIGPGP:pgpsig}\t%{RSAHEADER:pgpsig}"
    out = subprocess.run(["rpm", "-qp", "--nosignature", "--nodigest", "--qf", fmt, str(rpm)],
                         check=True, capture_output=True, text=True).stdout
    name, epoch, ver, rel, arch, sig1, sig2 = out.split("\t")
    signed = any(s and s != "(none)" for s in (sig1, sig2))
    return name, epoch, ver, rel, arch, signed


def vercmp(a, b):
    """rpmvercmp(): -1, 0 or 1, as rpm compares version or release strings."""
    if a == b:
        return 0
    seg = re.compile(r"(\d+|[a-zA-Z]+|~|\^)")
    x, y = seg.findall(a), seg.findall(b)
    while x or y:
        p, q = (x.pop(0) if x else None), (y.pop(0) if y else None)
        for mark in ("~", "^"):
            if p == mark or q == mark:
                if p != q:
                    if mark == "~":
                        return -1 if p == "~" else 1
                    if p is None:
                        return -1
                    if q is None:
                        return 1
                    return -1 if p == "^" else 1
                break
        else:
            if p is None or q is None:
                return 1 if q is None else -1
            if p.isdigit() != q.isdigit():
                return 1 if p.isdigit() else -1
            if p.isdigit():
                p, q = int(p), int(q)
            if p != q:
                return 1 if p > q else -1
    return 0


def newer(a, b):
    """(epoch, version, release) a sorts after b."""
    if int(a[0]) != int(b[0]):
        return int(a[0]) > int(b[0])
    return (vercmp(a[1], b[1]) or vercmp(a[2], b[2])) > 0


def write_if_changed(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_bytes() == data:
        return False
    path.write_bytes(data)
    return True


def update_redirects(entries):
    block = [BEGIN] + [f"/rpm/packages/{e['file']} {e['url']} 302" for e in entries] + [END]
    old = REDIRECTS.read_text() if REDIRECTS.exists() else ""
    keep, skipping = [], False
    for line in old.splitlines():
        if line == BEGIN:
            skipping = True
        elif line == END and skipping:
            skipping = False
        elif not skipping:
            keep.append(line)
    while keep and not keep[-1].strip():
        keep.pop()
    new = "\n".join(keep + ([""] if keep else []) + block) + "\n"
    write_if_changed(REDIRECTS, new.encode())


def gpg(key, *args):
    subprocess.run(["gpg", "--batch", "--yes", "--pinentry-mode", "loopback", "--passphrase", "",
                    "--local-user", key, "--digest-algo", "SHA512", *args], check=True)


def main():
    work = Path(tempfile.mkdtemp(prefix="rpm-repo-"))
    pkgs = work / "repo" / "packages"
    pkgs.mkdir(parents=True)
    best, dates = {}, []
    for repo in SOURCES:
        rel = api(f"/repos/{repo}/releases/latest")
        if not rel:
            print(f"{repo}: no published release, skipped")
            continue
        assets = [a for a in rel.get("assets", []) if a["name"].endswith(".rpm")]
        if not assets:
            print(f"{repo} {rel['tag_name']}: no .rpm assets, skipped")
            continue
        dates.append(rel["published_at"])
        for a in sorted(assets, key=lambda a: a["name"]):
            dest = work / f"{a['id']}.rpm"
            download(a["browser_download_url"], dest)
            name, epoch, ver, release, arch, signed = query(dest)
            print(f"{repo} {rel['tag_name']}: {a['name']} -> {name}-{ver}-{release}.{arch} signed={signed}")
            key = (name, arch)
            evr = (epoch, ver, release)
            if key in best and not newer(evr, best[key]["evr"]):
                continue
            best[key] = {"name": name, "evr": evr, "arch": arch, "signed": signed,
                         "file": f"{name}-{ver}-{release}.{arch}.rpm", "url": a["browser_download_url"],
                         "path": dest, "sha256": sha256(dest)}
    if not best:
        print("no .rpm assets on any source release yet; repository left as it is")
        return

    entries = sorted(best.values(), key=lambda e: (e["name"], e["arch"]))
    unsigned = [e["file"] for e in entries if not e["signed"]]
    if unsigned:
        print("WARNING: unsigned packages (gpgcheck=1 will reject them): " + ", ".join(unsigned))
    sources = json.dumps([{"file": e["file"], "url": e["url"], "sha256": e["sha256"]} for e in entries],
                         indent=2) + "\n"
    key = os.environ.get("RPM_KEY_ID")
    signed = (RPM / "repodata" / "repomd.xml.asc").exists()
    if (RPM / "sources.json").exists() and (RPM / "sources.json").read_text() == sources and signed:
        print("sources unchanged: metadata and signature kept")
    else:
        if not key:
            sys.exit("repository changed but RPM_KEY_ID is not set; cannot sign")
        for e in entries:
            shutil.copyfile(e["path"], pkgs / e["file"])
        revision = int(max(datetime.fromisoformat(d.replace("Z", "+00:00")) for d in dates).timestamp())
        subprocess.run(["createrepo_c", "--general-compress-type=gz", "--no-database",
                        "--revision", str(revision), "--set-timestamp-to-revision",
                        str(work / "repo")], check=True)
        if (RPM / "repodata").exists():
            shutil.rmtree(RPM / "repodata")
        shutil.copytree(work / "repo" / "repodata", RPM / "repodata")
        gpg(key, "--armor", "--detach-sign", "-o", str(RPM / "repodata" / "repomd.xml.asc"),
            str(RPM / "repodata" / "repomd.xml"))
        write_if_changed(RPM / "sources.json", sources.encode())
        print("metadata rebuilt and repomd.xml signed")

    write_if_changed(RPM / "freemkv.repo", REPO_FILE.encode())
    if key:
        pub = subprocess.run(["gpg", "--armor", "--export", key], check=True, capture_output=True).stdout
        write_if_changed(RPM / "freemkv.asc", pub)
    update_redirects(entries)


if __name__ == "__main__":
    main()
