#!/usr/bin/env python3
"""Build the freemkv pacman repository served at https://freemkv.org/arch.

Same design as scripts/apt-repo.py: only the database lives on the site; the
.pkg.tar.zst payloads (and their .sig) stay on GitHub releases and
public/_redirects sends /arch/<arch>/<file> to the release asset (302).

For every source repo, every *.pkg.tar.zst asset on its LATEST release is
picked up, any package, any architecture; nothing here names a package or an
arch. The newest version of each (name, arch) wins; `any` packages go into
every architecture. Output:

  public/arch/<arch>/freemkv.db{,.sig}      repo-add database (package signatures included)
  public/arch/<arch>/freemkv.files{,.sig}
  public/arch/freemkv.asc                   the signing key (same key as /apt and /rpm)
  public/arch/sources.json                  what the databases were built from
  public/_redirects                         (generated block between the BEGIN/END arch markers)

Deterministic: if sources.json would not change, nothing is rewritten or re-signed.

Needs (Arch Linux): python, repo-add, vercmp, bsdtar, gpg with the signing key
imported (ARCH_KEY_ID selects it). GH_TOKEN is used for the GitHub API if set.
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

SOURCES = ["freemkv/freemkv", "freemkv/freemkv-firmware"]
ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public"
ARCH = PUBLIC / "arch"
REPO = "freemkv"
REDIRECTS = PUBLIC / "_redirects"
BEGIN = "# BEGIN arch (generated by scripts/arch-repo.py; do not edit by hand)"
END = "# END arch"


def api(path):
    req = urllib.request.Request("https://api.github.com" + path)
    req.add_header("Accept", "application/vnd.github+json")
    tok = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
    if tok:
        req.add_header("Authorization", "Bearer " + tok)
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        raise


def download(url, dest):
    req = urllib.request.Request(url, headers={"Accept": "application/octet-stream"})
    with urllib.request.urlopen(req, timeout=600) as r, open(dest, "wb") as f:
        while chunk := r.read(1 << 20):
            f.write(chunk)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(1 << 20):
            h.update(chunk)
    return h.hexdigest()


def pkginfo(pkg):
    text = subprocess.run(["bsdtar", "-xOf", str(pkg), ".PKGINFO"], check=True,
                          capture_output=True, text=True).stdout
    info = {}
    for line in text.splitlines():
        if " = " in line and not line.startswith("#"):
            k, _, v = line.partition(" = ")
            info.setdefault(k, v)
    return info["pkgname"], info["pkgver"], info["arch"]


def newer(a, b):
    out = subprocess.run(["vercmp", a, b], check=True, capture_output=True, text=True).stdout
    return int(out) > 0


def write_if_changed(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_bytes() == data:
        return False
    path.write_bytes(data)
    return True


def update_redirects(lines):
    block = [BEGIN] + lines + [END]
    old = REDIRECTS.read_text() if REDIRECTS.exists() else ""
    keep, skipping = [], False
    for line in old.splitlines():
        if line == BEGIN:
            skipping = True
        elif line == END and skipping:
            skipping = False
        elif not skipping:
            keep.append(line)
    while keep and not keep[-1].strip():
        keep.pop()
    new = "\n".join(keep + ([""] if keep else []) + block) + "\n"
    write_if_changed(REDIRECTS, new.encode())


def main():
    work = Path(tempfile.mkdtemp(prefix="arch-repo-"))
    best = {}
    for repo in SOURCES:
        rel = api(f"/repos/{repo}/releases/latest")
        if not rel:
            print(f"{repo}: no published release, skipped")
            continue
        assets = {a["name"]: a for a in rel.get("assets", [])}
        pkgs = sorted(n for n in assets if n.endswith(".pkg.tar.zst"))
        if not pkgs:
            print(f"{repo} {rel['tag_name']}: no .pkg.tar.zst assets, skipped")
            continue
        for n in pkgs:
            a = assets[n]
            sig = assets.get(n + ".sig")
            if not sig:
                print(f"WARNING: {repo} {rel['tag_name']}: {n} has no .sig; skipped (pacman requires signatures)")
                continue
            dest = work / f"{a['id']}.pkg.tar.zst"
            download(a["browser_download_url"], dest)
            download(sig["browser_download_url"], Path(str(dest) + ".sig"))
            name, ver, arch = pkginfo(dest)
            print(f"{repo} {rel['tag_name']}: {n} -> {name} {ver} {arch}")
            key = (name, arch)
            if key in best and not newer(ver, best[key]["ver"]):
                continue
            best[key] = {"name": name, "ver": ver, "arch": arch, "path": dest,
                         "file": f"{name}-{ver}-{arch}.pkg.tar.zst",
                         "url": a["browser_download_url"], "sig_url": sig["browser_download_url"],
                         "sha256": sha256(dest)}
    if not best:
        print("no signed .pkg.tar.zst assets on any source release yet; repository left as it is")
        return

    entries = sorted(best.values(), key=lambda e: (e["name"], e["arch"]))
    arches = sorted({e["arch"] for e in entries if e["arch"] != "any"}) or ["x86_64"]
    sources = json.dumps([{"file": e["file"], "url": e["url"], "sha256": e["sha256"]} for e in entries],
                         indent=2) + "\n"
    key = os.environ.get("ARCH_KEY_ID")
    current = (ARCH / "sources.json").exists() and (ARCH / "sources.json").read_text() == sources
    if current and all((ARCH / a / f"{REPO}.db.sig").exists() for a in arches):
        print("sources unchanged: databases and signatures kept")
    else:
        if not key:
            sys.exit("repository changed but ARCH_KEY_ID is not set; cannot sign")
        for d in ARCH.iterdir() if ARCH.exists() else []:
            if d.is_dir() and d.name not in arches:
                shutil.rmtree(d)
        for arch in arches:
            stage = work / "repo" / arch
            stage.mkdir(parents=True)
            members = [e for e in entries if e["arch"] in (arch, "any")]
            for e in members:
                shutil.copyfile(e["path"], stage / e["file"])
                shutil.copyfile(str(e["path"]) + ".sig", stage / (e["file"] + ".sig"))
            subprocess.run(["repo-add", "--include-sigs", "--sign", "--key", key, "--verify",
                            str(stage / f"{REPO}.db.tar.gz"), *(str(stage / e["file"]) for e in members)],
                           check=True)
            out = ARCH / arch
            if out.exists():
                shutil.rmtree(out)
            out.mkdir(parents=True)
            # repo-add makes freemkv.db -> freemkv.db.tar.gz symlinks; the site needs real files.
            for name in (f"{REPO}.db", f"{REPO}.files"):
                for suffix in ("", ".sig"):
                    shutil.copyfile(stage / f"{name}.tar.gz{suffix}", out / f"{name}{suffix}")
        write_if_changed(ARCH / "sources.json", sources.encode())
        print("databases rebuilt and signed for " + ", ".join(arches))

    if key:
        pub = subprocess.run(["gpg", "--armor", "--export", key], check=True, capture_output=True).stdout
        write_if_changed(ARCH / f"{REPO}.asc", pub)
    lines = []
    for arch in arches:
        for e in entries:
            if e["arch"] in (arch, "any"):
                lines.append(f"/arch/{arch}/{e['file']} {e['url']} 302")
                lines.append(f"/arch/{arch}/{e['file']}.sig {e['sig_url']} 302")
    update_redirects(lines)


if __name__ == "__main__":
    main()
